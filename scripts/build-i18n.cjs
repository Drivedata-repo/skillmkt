const fs = require("node:fs");
const core = require("../dist/i18n-core.js");
const publicUI = require("../data/i18n-public.cjs");
const marketUI = require("../data/i18n-market.cjs");
const { messages } = require("../lib/locale.cjs");
const dictionary = { ...messages, ...marketUI, ...publicUI };
const placeholders = (s) =>
  [...new Set(s.match(/\{[a-zA-Z][a-zA-Z0-9_]*\}/g) || [])].sort().join(",");
for (const [key, translations] of Object.entries(dictionary)) {
  if (key !== core.normalize(key))
    throw new Error("Unnormalized i18n key: " + key);
  if (
    !Array.isArray(translations) ||
    translations.length !== 2 ||
    translations.some((s) => typeof s !== "string" || !s.trim())
  )
    throw new Error("Missing translation: " + key);
  for (const text of translations)
    if (placeholders(key) !== placeholders(text))
      throw new Error("Mismatched i18n placeholders: " + key);
}
fs.writeFileSync(
  "dist/translations.js",
  "// Generated by scripts/build-i18n.cjs. No private catalog data.\nwindow.DeckTranslations = " +
    JSON.stringify(dictionary) +
    ";\n",
);
console.log(
  `${Object.keys(dictionary).length} interface strings verified in English and Spanish`,
);
