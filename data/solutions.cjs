const normalize = (s) =>
  String(s || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
function recommend(input) {
  const text = normalize(input.pain + " " + (input.systems || ""));
  return SOLUTIONS.filter(
    (s) => input.audience === "technical" || s.audience !== "technical",
  )
    .map((s) => {
      const hits = s.keywords.filter((k) => {
        const n = normalize(k);
        return new RegExp(
          "(^|[^a-z0-9])" +
            n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") +
            "(?:s|es)?([^a-z0-9]|$)",
        ).test(text);
      });
      const area = s.category === input.area;
      return {
        solution: s,
        score: hits.length * 3 + (area ? 2 : 0),
        hits,
        area,
      };
    })
    .filter((r) => r.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);
}
